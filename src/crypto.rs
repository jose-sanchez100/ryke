use sha1::Sha1;
use sha2::{Sha256, Sha384, Sha512};
use x25519_dalek::{PublicKey, StaticSecret};
use zeroize::Zeroize;

/// A negotiated PRF (RFC 7296 §3.3.2 Transform Type 2). Used for `prf`/`prf+`
/// throughout the key schedule *and* for the AUTH/MACedIDFor* payloads
/// (RFC 7296 §2.15), which must use whatever PRF `IKE_SA_INIT` actually
/// negotiated rather than a fixed algorithm.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PrfAlgorithm {
    Md5,
    Sha1,
    Sha256,
    Sha384,
    Sha512,
}

impl PrfAlgorithm {
    pub fn from_transform_id(id: u16) -> Option<PrfAlgorithm> {
        use crate::ikev2::payload::transform_id as t;
        match id {
            t::PRF_HMAC_MD5 => Some(PrfAlgorithm::Md5),
            t::PRF_HMAC_SHA1 => Some(PrfAlgorithm::Sha1),
            t::PRF_HMAC_SHA2_256 => Some(PrfAlgorithm::Sha256),
            t::PRF_HMAC_SHA2_384 => Some(PrfAlgorithm::Sha384),
            t::PRF_HMAC_SHA2_512 => Some(PrfAlgorithm::Sha512),
            _ => None,
        }
    }

    pub fn transform_id(self) -> u16 {
        use crate::ikev2::payload::transform_id as t;
        match self {
            PrfAlgorithm::Md5 => t::PRF_HMAC_MD5,
            PrfAlgorithm::Sha1 => t::PRF_HMAC_SHA1,
            PrfAlgorithm::Sha256 => t::PRF_HMAC_SHA2_256,
            PrfAlgorithm::Sha384 => t::PRF_HMAC_SHA2_384,
            PrfAlgorithm::Sha512 => t::PRF_HMAC_SHA2_512,
        }
    }

    /// HMAC output length in bytes — also the PRF's own key length
    /// (SK_d/SK_pi/SK_pr) per RFC 7296 §2.13.
    pub fn output_len(self) -> usize {
        match self {
            PrfAlgorithm::Md5 => 16,
            PrfAlgorithm::Sha1 => 20,
            PrfAlgorithm::Sha256 => 32,
            PrfAlgorithm::Sha384 => 48,
            PrfAlgorithm::Sha512 => 64,
        }
    }
}

/// A negotiated non-AEAD integrity algorithm (RFC 7296 §3.3.2 Transform
/// Type 3). Meaningless alongside an AEAD cipher (AES-GCM/ChaCha20-Poly1305),
/// which provides its own integrity check.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IntegAlgorithm {
    HmacMd5_96,
    HmacSha1_96,
    HmacSha2_256_128,
    HmacSha2_384_192,
    HmacSha2_512_256,
}

impl IntegAlgorithm {
    pub fn from_transform_id(id: u16) -> Option<IntegAlgorithm> {
        use crate::ikev2::payload::transform_id as t;
        match id {
            t::AUTH_HMAC_MD5_96 => Some(IntegAlgorithm::HmacMd5_96),
            t::AUTH_HMAC_SHA1_96 => Some(IntegAlgorithm::HmacSha1_96),
            t::AUTH_HMAC_SHA2_256_128 => Some(IntegAlgorithm::HmacSha2_256_128),
            t::AUTH_HMAC_SHA2_384_192 => Some(IntegAlgorithm::HmacSha2_384_192),
            t::AUTH_HMAC_SHA2_512_256 => Some(IntegAlgorithm::HmacSha2_512_256),
            _ => None,
        }
    }

    pub fn transform_id(self) -> u16 {
        use crate::ikev2::payload::transform_id as t;
        match self {
            IntegAlgorithm::HmacMd5_96 => t::AUTH_HMAC_MD5_96,
            IntegAlgorithm::HmacSha1_96 => t::AUTH_HMAC_SHA1_96,
            IntegAlgorithm::HmacSha2_256_128 => t::AUTH_HMAC_SHA2_256_128,
            IntegAlgorithm::HmacSha2_384_192 => t::AUTH_HMAC_SHA2_384_192,
            IntegAlgorithm::HmacSha2_512_256 => t::AUTH_HMAC_SHA2_512_256,
        }
    }

    /// The HMAC key length -- the full underlying hash output length (RFC
    /// 7296 §3.3.2), *not* the truncated ICV length below.
    pub fn key_len(self) -> usize {
        match self {
            IntegAlgorithm::HmacMd5_96 => 16,
            IntegAlgorithm::HmacSha1_96 => 20,
            IntegAlgorithm::HmacSha2_256_128 => 32,
            IntegAlgorithm::HmacSha2_384_192 => 48,
            IntegAlgorithm::HmacSha2_512_256 => 64,
        }
    }

    /// The truncated ICV length appended to the wire (RFC 4868 §2.6 for the
    /// SHA-2 variants, RFC 2404/2403 for SHA-1-96/MD5-96).
    pub fn icv_len(self) -> usize {
        match self {
            IntegAlgorithm::HmacMd5_96 => 12,
            IntegAlgorithm::HmacSha1_96 => 12,
            IntegAlgorithm::HmacSha2_256_128 => 16,
            IntegAlgorithm::HmacSha2_384_192 => 24,
            IntegAlgorithm::HmacSha2_512_256 => 32,
        }
    }

    /// Compute the truncated HMAC ICV over `data` under `key` (`key.len()`
    /// should be [`Self::key_len`], though HMAC itself accepts any length).
    pub fn compute(self, key: &[u8], data: &[u8]) -> Vec<u8> {
        let full = match self {
            IntegAlgorithm::HmacMd5_96 => {
                let mut m = Hmac::<Md5>::new_from_slice(key).expect("HMAC accepts any key length");
                m.update(data);
                m.finalize().into_bytes().to_vec()
            }
            IntegAlgorithm::HmacSha1_96 => {
                let mut m = Hmac::<Sha1>::new_from_slice(key).expect("HMAC accepts any key length");
                m.update(data);
                m.finalize().into_bytes().to_vec()
            }
            IntegAlgorithm::HmacSha2_256_128 => {
                let mut m = Hmac::<Sha256>::new_from_slice(key).expect("HMAC accepts any key length");
                m.update(data);
                m.finalize().into_bytes().to_vec()
            }
            IntegAlgorithm::HmacSha2_384_192 => {
                let mut m = Hmac::<Sha384>::new_from_slice(key).expect("HMAC accepts any key length");
                m.update(data);
                m.finalize().into_bytes().to_vec()
            }
            IntegAlgorithm::HmacSha2_512_256 => {
                let mut m = Hmac::<Sha512>::new_from_slice(key).expect("HMAC accepts any key length");
                m.update(data);
                m.finalize().into_bytes().to_vec()
            }
        };
        full[..self.icv_len()].to_vec()
    }
}

